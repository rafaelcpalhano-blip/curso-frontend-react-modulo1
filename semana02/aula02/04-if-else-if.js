//APROVAÇÃO MEDIA MAIOR QUE 7
//RECUPERAÇÃO MEDIA ENTRE 5 E 7
//REPROVADO MEDIA MENOR QUE 5

const media = 4

if (media >= 7)
{
    console.log("Aprovado!")
} else if (media >= 5 && media < 7)
{
    console.log("Em recuperação!")
} else
{
    console.log("Reprovado!")
}